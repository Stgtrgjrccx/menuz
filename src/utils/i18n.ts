/**
 * Universal Intelligent helper that translates any dish name, description, chef note, and story dynamically
 */
export function getTranslatedDish(dish: any, lang: Language): any {
  if (!dish || lang === 'en') return dish;

  let translatedName = dish.name;
  let translatedDesc = dish.short_description || dish.full_description || '';
  let translatedFullDesc = dish.full_description || dish.short_description || '';
  let translatedStory = dish.chef_story || '';
  let translatedNotes = dish.chef_notes || '';

  // 1. Exact or partial match in dish dictionary
  let matched = false;
  const rawLower = (dish.name || '').toLowerCase().trim();

  for (const [key, map] of Object.entries(DISH_TRANSLATIONS)) {
    const kLower = key.toLowerCase();
    if ((rawLower === kLower || rawLower.includes(kLower) || kLower.includes(rawLower)) && map[lang]) {
      const match = map[lang]!;
      translatedName = match.name || dish.name;
      if (match.desc) {
        translatedDesc = match.desc;
        translatedFullDesc = match.desc;
      }
      if (match.notes) translatedNotes = match.notes;
      matched = true;
      break;
    }
  }

  // 2. Intelligent culinary fallback for Hindi and Marathi
  if (!matched && (lang === 'hi' || lang === 'mr')) {
    let replacedName = dish.name;
    for (const [vocab, tr] of Object.entries(CULINARY_VOCABULARY)) {
      const regex = new RegExp(`\\b${vocab}\\b`, 'gi');
      if (regex.test(replacedName)) {
        replacedName = replacedName.replace(regex, tr[lang]);
      }
    }
    if (replacedName !== dish.name) {
      translatedName = replacedName;
    }
  }

  // Dietary translation
  const translatedDietary = (dish.dietary_flags || []).map((f: string) => {
    const lower = f.toLowerCase();
    if (lower.includes('veg') && !lower.includes('non')) {
      return TRANSLATIONS[lang]?.filterVeg || 'Pure Veg';
    }
    if (lower.includes('non_veg') || lower.includes('non-veg') || lower.includes('non vegetarian')) {
      return TRANSLATIONS[lang]?.filterNonVeg || 'Non-Veg';
    }
    if (lower.includes('gluten')) {
      return TRANSLATIONS[lang]?.filterGlutenFree || 'Gluten-Free';
    }
    if (lower.includes('vegan')) {
      return TRANSLATIONS[lang]?.filterVegan || 'Vegan';
    }
    if (lower.includes('jain')) {
      return TRANSLATIONS[lang]?.filterJain || 'Jain';
    }
    if (lower.includes('halal')) {
      return TRANSLATIONS[lang]?.filterHalal || 'Halal';
    }
    return f;
  });

  return {
    ...dish,
    name: translatedName,
    short_description: translatedDesc,
    full_description: translatedFullDesc,
    chef_story: translatedStory || dish.chef_story,
    chef_notes: translatedNotes || dish.chef_notes,
    dietary_flags: translatedDietary
  };
}

export function translateDishName(name: string, lang: Language): string {
  if (!name || lang === 'en') return name;
  const dummy = { name, short_description: '' };
  return getTranslatedDish(dummy, lang).name;
}

